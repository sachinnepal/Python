import numpy as np

array1 = np.array([1, 2, 3])
array2 = np.array([4, 6, 5])


# -------------------------------
# 1. ADDITION
# -------------------------------

print(array1 + array2)
# [5 8 8]


# -------------------------------
# 2. SUBTRACTION
# -------------------------------

print(array1 - array2)
# [-3 -4 -2]


# -------------------------------
# 3. MULTIPLICATION
# -------------------------------

print(array1 * array2)
# [4 12 15]


# -------------------------------
# 4. DIVISION
# -------------------------------

print(array2 / array1)
# [4.  3.  1.66666667]


# -------------------------------
# 5. FLOOR DIVISION
# -------------------------------

print(array2 // array1)
# [4 3 1]


# -------------------------------
# 6. MODULUS / REMAINDER
# -------------------------------

print(array2 % array1)
# [0 0 2]

# 4 % 1 = 0
# 6 % 2 = 0
# 5 % 3 = 2


# -------------------------------
# 7. POWER
# -------------------------------

print(array1 ** 2)
# [1 4 9]

# 1² = 1
# 2² = 4
# 3² = 9


# Power using two arrays

print(array1 ** array2)
# [  1  64 243]

# 1⁴ = 1
# 2⁶ = 64
# 3⁵ = 243


# -------------------------------
# 8. NEGATIVE
# -------------------------------

print(-array1)
# [-1 -2 -3]


# -------------------------------
# 9. ABSOLUTE VALUE
# -------------------------------

array3 = np.array([-10, 20, -30])

print(np.abs(array3))
# [10 20 30]


# -------------------------------
# 10. SQUARE ROOT
# -------------------------------

print(np.sqrt(array1))
# [1.         1.41421356 1.73205081]


# -------------------------------
# 11. SUM
# -------------------------------

print(np.sum(array1))
# 6

# 1 + 2 + 3 = 6


# -------------------------------
# 12. MINIMUM
# -------------------------------

print(np.min(array1))
# 1


# -------------------------------
# 13. MAXIMUM
# -------------------------------

print(np.max(array1))
# 3


# -------------------------------
# 14. MEAN / AVERAGE
# -------------------------------

print(np.mean(array1))
# 2.0

# (1 + 2 + 3) / 3 = 2


# -------------------------------
# 15. MEDIAN
# -------------------------------

print(np.median(array1))
# 2.0


# -------------------------------
# 16. STANDARD DEVIATION
# -------------------------------

print(np.std(array1))
# 0.81649658


# -------------------------------
# 17. VARIANCE
# -------------------------------

print(np.var(array1))
# 0.66666667


# -------------------------------
# 18. COMPARISON
# -------------------------------

print(array1 > array2)
# [False False False]

# 1 > 4 → False
# 2 > 6 → False
# 3 > 5 → False


print(array1 < array2)
# [ True  True  True]


print(array1 == array2)
# [False False False]


# -------------------------------
# 19. LOGICAL OPERATIONS
# -------------------------------

print((array1 > 1) & (array2 > 4))
# [False  True  True]

# & means AND


print((array1 > 1) | (array2 > 5))
# [False  True  True]

# | means OR